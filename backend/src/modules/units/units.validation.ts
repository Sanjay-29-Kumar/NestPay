import { z } from "zod";

const unitTypeEnum = z.enum([
    "FLAT",
    "ROOM",
    "SHOP",
    "OFFICE",
    "SUITE",
    "VILLA",
    "BLOCK",
    "FLOOR",
    "ONE_RK",
    "ONE_BHK",
    "TWO_BHK",
    "THREE_BHK",
    "SHARED_ROOM",
    "BED_SPACE",
    "LINE_UNIT",
]);

export const createUnitSchema = z.object({
    body: z.object({
        propertyId: z.string().optional(),
        unitNumber: z.string({ message: "Unit number is required" }).min(1).max(50).trim(),
        blockWing: z.string().optional(),
        roomType: z.string().optional(),
        unitType: z.string().optional(),
        floor: z.string().optional(),
        areaSqFt: z.number().min(0).optional(),
        bedrooms: z.number().min(0).optional(),
        bathrooms: z.number().min(0).optional(),
        maxCapacity: z.number().min(1).optional(),
        sharingType: z.enum(["PRIVATE", "DOUBLE_SHARING", "TRIPLE_SHARING", "MULTI_SHARING"]).optional(),
        occupancyType: z.enum(["Single", "Family", "Sharing"]).optional(),
        rentAmount: z.number().min(0).optional(),
        depositAmount: z.number().min(0).optional(),
        maintenanceCharge: z.number().min(0).optional(),
        furnishingStatus: z.enum(["Unfurnished", "Semi-Furnished", "Fully Furnished"]).optional(),
        amenities: z.array(z.string()).optional(),
        photos: z.array(z.string()).optional(),
        notes: z.string().optional(),
    }),
});

export const updateUnitSchema = z.object({
    body: z.object({
        unitNumber: z.string().min(1).max(50).trim().optional(),
        blockWing: z.string().optional(),
        roomType: z.string().optional(),
        unitType: z.string().optional(),
        floor: z.string().optional(),
        areaSqFt: z.number().min(0).optional(),
        bedrooms: z.number().min(0).optional(),
        bathrooms: z.number().min(0).optional(),
        maxCapacity: z.number().min(1).optional(),
        sharingType: z.enum(["PRIVATE", "DOUBLE_SHARING", "TRIPLE_SHARING", "MULTI_SHARING"]).optional(),
        occupancyType: z.enum(["Single", "Family", "Sharing"]).optional(),
        rentAmount: z.number().min(0).optional(),
        depositAmount: z.number().min(0).optional(),
        maintenanceCharge: z.number().min(0).optional(),
        furnishingStatus: z.enum(["Unfurnished", "Semi-Furnished", "Fully Furnished"]).optional(),
        amenities: z.array(z.string()).optional(),
        photos: z.array(z.string()).optional(),
        notes: z.string().optional(),
        status: z.enum(["VACANT", "OCCUPIED", "MAINTENANCE", "RESERVED"]).optional(),
    }),
});
